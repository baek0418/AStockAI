_RESEARCH_PROFILES = _CORE_RESEARCH_PROFILES + tuple(
    _master_profile(*spec) for spec in _MASTER_PROFILE_SPECS
)


def research_profile_catalog(period=None, include_details=False):
    """返回研究框架目录；默认隐藏来源、外部 skill 与适用边界。"""
    profiles = [deepcopy(item) for item in _RESEARCH_PROFILES]
    if period and period != "全部":
        profiles = [item for item in profiles if item["周期标签"] == period]
    for item in profiles:
        item.pop("验证项", None)
        if not include_details:
            for field in ("外部 Skill", "适用边界", "来源说明"):
                item.pop(field, None)
    return profiles


def get_research_profile(profile_id=None):
    """按标识取研究框架；未知标识安全回退至短线动量观察。"""
    requested = profile_id or DEFAULT_RESEARCH_PROFILE_ID
    profile = next((item for item in _RESEARCH_PROFILES if item["id"] == requested), None)
    return deepcopy(profile or _RESEARCH_PROFILES[0])
